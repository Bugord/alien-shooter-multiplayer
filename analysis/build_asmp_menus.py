"""Builds the multiplayer menus: asmp_play.men (the form), asmp_lobby.men (the room)
and the multiplayer entry of asmp_mainmenu.men.

The .men format (Alien Shooter menu resource), as far as these files use it:

    "RES " u32 size-of-rest
    "MENUHEAD" u32 36, 36 bytes of screen header
    "SPR " u32 size-of-rest, 12-byte pre-header (third word: record count
           including the terminator), then the records
    record: u32 length (not counting itself), then
        u32 pointer (stale editor value), u32 VID, f32 x, f32 y, f32 scale,
        u32 direction byte, 12 zero bytes,
        text VIDs only: u32 behaviour flags, zero-terminated string
    terminator: u32 4, u32 0xFFFFFFFF

Text flags are the script's BEH_* values (EXPORT.LGC): alignment (1 centre x,
2 right, 8 centre y) plus where the string comes from (0 literal, 16 strings.ini
keyword, 96 a script variable updated every frame). Strings are in the game's
cp1251. The text font comes from the VID: 2 status, 3 button label, 4 caption.

The script finds buttons and arrows by ndir, stored as the byte ndir*256/10
(1 -> 25). The DLL finds texts by VID and the raw direction byte; those numbers
come from asmp-dll/src/multiplayer/menu_layout.h, which this tool reads, so the
menus and the DLL cannot drift apart. Every visible string lives here: the DLL
composes its texts from the menu's text bank (off-screen captions at
MENU_BANK_DIR + id) plus ASCII names and numbers.

Menu coordinates: x 446 is the screen centre; y is relative to the centre and a
480-pixel-high render shows about -210..270.

The tool is idempotent: the form and the room are built from scratch on the
header of the existing asmp_play.men, and the main menu entry is renamed in place.

Usage: python analysis/build_asmp_menus.py [--check]
  --check  only compares the generated bytes with the files; exit 1 if they differ.
"""

