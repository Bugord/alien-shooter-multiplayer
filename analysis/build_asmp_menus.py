def read_layout(path=LAYOUT_PATH):
    """Returns {name: value} of the MENU_* defines and enum entries of menu_layout.h."""
    source = path.read_text(encoding="utf-8")
    values = {}
    for name, value in re.findall(r"#define\s+(MENU_\w+)\s+(-?\d+)\b", source):
        values[name] = int(value)
    for name, value in re.findall(r"\b(MENU_TEXT_\w+)\s*=\s*(\d+)", source):
        values[name] = int(value)
    for name, alias in re.findall(r"#define\s+(MENU_\w+)\s+(MENU_[A-Z_]+)\s", source):
        values[name] = values[alias]
    return values


LAYOUT = read_layout()


def layout(name):
    return LAYOUT["MENU_" + name]


def ndir_byte(ndir):
    """The direction byte the script's MenuFind and MenuNDirUnderCursor expect."""
    return ndir * 256 // 10


class Record:
    """One SPR record; `body` is everything after the length word."""

    def __init__(self, body):
        self.body = bytearray(body)

    @property
    def vid(self):
        return struct.unpack_from("<I", self.body, 4)[0]

    @property
    def direction(self):
        return struct.unpack_from("<I", self.body, 20)[0]

    @property
    def text(self):
        if len(self.body) <= SPRITE_BODY_LENGTH + 4:
            return None
        raw = bytes(self.body[SPRITE_BODY_LENGTH + 4:])
        return raw.split(b"\0", 1)[0].decode(ENCODING)

    def set_text(self, text):
        flags = self.body[SPRITE_BODY_LENGTH:SPRITE_BODY_LENGTH + 4]
        self.body = self.body[:SPRITE_BODY_LENGTH] + flags + text.encode(ENCODING) + b"\0"

    def encode(self):
        return struct.pack("<I", len(self.body)) + bytes(self.body)


def make_sprite(vid, x, y, direction, scale=1.0):
    body = struct.pack("<IIfffI", 0, vid, x, y, scale, direction) + bytes(12)
    return Record(body)


def make_text(vid, x, y, direction, flags, text, scale=0.0):
    body = struct.pack("<IIfffI", 0, vid, x, y, scale, direction) + bytes(12)
    body += struct.pack("<I", flags) + text.encode(ENCODING) + b"\0"
    return Record(body)


def caption(x, y, text, direction=0, align=ALIGN_CENTER):
    return make_text(layout("VID_CAPTION"), x, y, direction, align, text)


def label(x, y, text, direction=0, align=ALIGN_CENTER):
    return make_text(layout("VID_LABEL"), x, y, direction, align, text)


def button(x, y, ndir, text, label_direction=0):
    """A button and its label; an empty text leaves the label for the DLL."""
    return [
        make_sprite(VID_BUTTON, x, y, ndir_byte(ndir)),
        label(x + LABEL_DX, y - LABEL_RISE, text, label_direction),
    ]


def selector(x, y, first_arrow_ndir, value_direction):
    """The game's arrow selector (play.men difficulty): bar, two arrows, value text.
    Even arrow ndirs point left, odd ones right."""
    return [
        make_sprite(VID_SELECTOR_BAR, x, y, 0),
        make_sprite(VID_ARROW, x - ARROW_OFFSET, y, ndir_byte(first_arrow_ndir)),
        make_sprite(VID_ARROW, x + ARROW_OFFSET, y, ndir_byte(first_arrow_ndir + 1)),
        label(x, y - LABEL_RISE, "", value_direction),
    ]


def bank(strings):
    """Off-screen captions the DLL reads by id."""
    records = []
    for name, text in strings.items():
        direction = layout("BANK_DIR") + layout("TEXT_" + name)
        records.append(caption(BANK_X, BANK_Y, text, direction))
    return records


def mode_bank():
    records = []
    for mode, keyword in enumerate(MODE_KEYWORDS):
        direction = layout("BANK_DIR") + layout("TEXT_MODE_CAMPAIGN") + mode
        records.append(make_text(layout("VID_CAPTION"), BANK_X, BANK_Y, direction,
                                 ALIGN_CENTER | FROM_STRINGS_INI, keyword))
    return records


def status_line(y):
    """The status entity the script and the DLL exchange codes through, and the line
    the DLL writes. The status font has no Cyrillic, so the line is a caption."""
    x = CENTER_X
    return [
        make_text(layout("VID_STATUS"), x, y, layout("DIR_STATUS"), ALIGN_CENTER, ""),
        caption(x, y, "", layout("DIR_STATUS_TEXT")),
    ]


def edit_field(x, y, ndir, text_direction, variable):
    """An edit box (VID 708) and the script variable it shows (asmp_play.lgc)."""
