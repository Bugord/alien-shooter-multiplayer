def parse(data):
    """Returns (bytes before the records, list of records)."""
    if data[:4] != b"RES " or data[8:16] != b"MENUHEAD":
        raise ValueError("not a menu resource")
    head_length = struct.unpack_from("<I", data, 16)[0]
    spr_at = 20 + head_length
    if data[spr_at:spr_at + 4] != b"SPR ":
        raise ValueError("SPR section not found")

    position = spr_at + 8 + 12
    prefix = data[:position]
    records = []
    while True:
        length = struct.unpack_from("<I", data, position)[0]
        if length == 4:
            break
        records.append(Record(data[position + 4:position + 4 + length]))
        position += 4 + length

    if position + len(TERMINATOR) != len(data):
        raise ValueError("data after the terminator")
    count = struct.unpack_from("<I", data, spr_at + 8 + 8)[0]
    if count != len(records) + 1:
        raise ValueError("record count does not match the pre-header")
    return prefix, records


def build(prefix, records):
    """Writes the records after `prefix`, fixing the sizes and the record count."""
    head_length = struct.unpack_from("<I", prefix, 16)[0]
    spr_at = 20 + head_length
    body = b"".join(record.encode() for record in records) + TERMINATOR

    out = bytearray(prefix)
    struct.pack_into("<I", out, spr_at + 8 + 8, len(records) + 1)
    out += body
    struct.pack_into("<I", out, spr_at + 4, len(out) - spr_at - 8)
    struct.pack_into("<I", out, 4, len(out) - 8)
    return bytes(out)


def main_menu_records(records):
    """Renames the multiplayer entry so it reads like the game's other entries."""
    for record in records:
        if record.vid == layout("VID_LABEL") and record.text in (MAIN_MENU_ENTRY_OLD,
                                                                 MAIN_MENU_ENTRY):
            record.set_text(MAIN_MENU_ENTRY)
            return records
    raise ValueError("multiplayer entry not found in " + MAIN_MENU_PATH.name)


def describe(name, records):
    print(name)
    for record in records:
        x, y = struct.unpack_from("<ff", record.body, 8)
        text = record.text
        shown = f" {text!r}" if text is not None else ""
        print(f"  vid={record.vid:4} dir={record.direction:3} x={x:7.1f} y={y:7.1f}{shown}")


def main(arguments):
    check_only = "--check" in arguments
    prefix, _ = parse(FORM_PATH.read_bytes())
    main_prefix, main_records = parse(MAIN_MENU_PATH.read_bytes())

    form = form_records()
    lobby = lobby_records()
    main_menu = main_menu_records(main_records)
    outputs = {
        FORM_PATH: build(prefix, form),
        LOBBY_PATH: build(prefix, lobby),
        MAIN_MENU_PATH: build(main_prefix, main_menu),
    }

    if check_only:
        stale = [path.name for path, data in outputs.items()
                 if not path.exists() or path.read_bytes() != data]
        if stale:
            print("out of date: " + ", ".join(stale))
            return 1
        print("menus are up to date")
        return 0

    for path, data in outputs.items():
        path.write_bytes(data)
    describe(FORM_PATH.name, form)
    describe(LOBBY_PATH.name, lobby)
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
