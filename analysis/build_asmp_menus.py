"""Builds the multiplayer menu layouts from game/AlienShooter/Maps/asmp_play.men.

The .men format (Alien Shooter menu resource), as far as these files use it:

    "RES " u32 size-of-rest
    "MENUHEAD" u32 36, 36 bytes of screen header
    "SPR " u32 size-of-rest, 12-byte pre-header (third word: record count
           including the terminator), then the records
    record: u32 length (not counting itself), then
        u32 pointer (stale editor value), u32 VID, f32 x, f32 y, f32 scale,
        u32 direction byte, 12 zero bytes,
        text VIDs only: u32 font flags, zero-terminated string
    terminator: u32 4, u32 0xFFFFFFFF

The script's MenuFind(vid, ndir) and MenuNDirUnderCursor() use the direction byte
ndir*256/10 (1 -> 25). This works for buttons; a status text at byte 25 was not
found in the live test, so both status texts stay at byte 0 and the DLL tells the
room menu apart by the direction byte of its action label (ROOM_MARKER_DIR).
The text font comes from the VID: 3 is the button label font, 4 the caption font.

The tool is idempotent: it removes the records it added before adding them again.
It rewrites asmp_play.men (adds the Create button) and asmp_lobby.men (the room).

Usage: python analysis/build_asmp_menus.py [--check]
  --check  only compares the generated bytes with the files; exit 1 if they differ.
"""

import struct
import sys
from pathlib import Path

MAPS = Path(__file__).resolve().parent.parent / "game" / "AlienShooter" / "Maps"
FORM_PATH = MAPS / "asmp_play.men"
LOBBY_PATH = MAPS / "asmp_lobby.men"

# VIDs used by the menu.
VID_STATUS_TEXT = 2   # Text bound to a script variable, health field = status code.
VID_STATIC_TEXT = 3   # Button label font; literal, string-table or variable text.
VID_FIGURE_MALE = 706
VID_FIGURE_FEMALE = 707
VID_BUTTON = 705
VID_EDITBOX = 708

# Font flag words copied from the existing records.
FONT_LITERAL = 0x09       # "CONNECT"
FONT_VARIABLE = 0x69      # "asmpStrConnecting", "asmpStrName"

# Direction bytes: ndir * 256 / 10.
NDIR_1 = 25
NDIR_2 = 51
NDIR_3 = 76

SPRITE_BODY_LENGTH = 36
TERMINATOR = struct.pack("<II", 4, 0xFFFFFFFF)

# Raw direction byte of the room menu's action label; session.c ROOM_MARKER_DIR.
ROOM_MARKER_DIR = 5

# Layout. Menu y is relative to the screen centre: a 480-pixel-high render shows
# y up to about 230, so the three form buttons are stacked 36 apart (the main menu
# uses 30) and the status line moves above them.
BUTTON_X = 446.0
LABEL_X = 447.0
STATUS_Y = 100.0
ROW_STEP = 36.0
FIRST_BUTTON_Y = 131.0
SECOND_BUTTON_Y = FIRST_BUTTON_Y + ROW_STEP
THIRD_BUTTON_Y = SECOND_BUTTON_Y + ROW_STEP
LABEL_RISE = 1.0          # Labels sit one pixel above their button ("CONNECT").
STRING_LABEL_RISE = 2.0   # String-table labels sit two pixels above ("MainMenu").


class Record:
    """One SPR record; `body` is everything after the length word."""

    def __init__(self, body):
        self.body = bytearray(body)

    @property
    def vid(self):
        return struct.unpack_from("<I", self.body, 4)[0]

    @property
    def direction(self):
        return struct.unpack_from("<I", self.body, 20)[0]

    @property
    def text(self):
        if len(self.body) <= SPRITE_BODY_LENGTH + 4:
            return None
        raw = bytes(self.body[SPRITE_BODY_LENGTH + 4:])
        return raw.split(b"\0", 1)[0].decode("latin-1")

    def move(self, x, y):
        struct.pack_into("<ff", self.body, 8, x, y)

    def encode(self):
        return struct.pack("<I", len(self.body)) + bytes(self.body)


def make_sprite(vid, x, y, direction):
    body = struct.pack("<IIfffI", 0, vid, x, y, 1.0, direction) + bytes(12)
    return Record(body)


def make_text(vid, x, y, direction, font, text):
    body = struct.pack("<IIfffI", 0, vid, x, y, 0.0, direction) + bytes(12)
    body += struct.pack("<I", font) + text.encode("latin-1") + b"\0"
    return Record(body)


def parse(data):
    """Returns (bytes before the records, list of records)."""
    if data[:4] != b"RES " or data[8:16] != b"MENUHEAD":
        raise ValueError("not a menu resource")
    head_length = struct.unpack_from("<I", data, 16)[0]
    spr_at = 20 + head_length
    if data[spr_at:spr_at + 4] != b"SPR ":
        raise ValueError("SPR section not found")

    position = spr_at + 8 + 12
    prefix = data[:position]
    records = []
    while True:
        length = struct.unpack_from("<I", data, position)[0]
        if length == 4:
            break
        records.append(Record(data[position + 4:position + 4 + length]))
        position += 4 + length

    if position + len(TERMINATOR) != len(data):
        raise ValueError("data after the terminator")
    count = struct.unpack_from("<I", data, spr_at + 8 + 8)[0]
    if count != len(records) + 1:
        raise ValueError("record count does not match the pre-header")
    return prefix, records


def build(prefix, records):
    """Writes the records after `prefix`, fixing the sizes and the record count."""
    head_length = struct.unpack_from("<I", prefix, 16)[0]
    spr_at = 20 + head_length
    body = b"".join(record.encode() for record in records) + TERMINATOR

    out = bytearray(prefix)
    struct.pack_into("<I", out, spr_at + 8 + 8, len(records) + 1)
    out += body
    struct.pack_into("<I", out, spr_at + 4, len(out) - spr_at - 8)
    struct.pack_into("<I", out, 4, len(out) - 8)
    return bytes(out)


def is_create_record(record):
    if record.vid == VID_BUTTON and record.direction == NDIR_3:
        return True
    return record.vid == VID_STATIC_TEXT and record.text == "CREATE"


def place_form_record(record):
    """Moves the original buttons, labels and status into the three-button layout."""
    if record.vid == VID_BUTTON and record.direction == NDIR_1:
        record.move(BUTTON_X, FIRST_BUTTON_Y)
    elif record.vid == VID_STATIC_TEXT and record.text == "CONNECT":
        record.move(LABEL_X, FIRST_BUTTON_Y - LABEL_RISE)
    elif record.vid == VID_BUTTON and record.direction == NDIR_2:
        record.move(BUTTON_X, THIRD_BUTTON_Y)
    elif record.vid == VID_STATIC_TEXT and record.text == "MainMenu":
        record.move(LABEL_X, THIRD_BUTTON_Y - STRING_LABEL_RISE)
    elif record.vid == VID_STATUS_TEXT:
        record.move(LABEL_X, STATUS_Y)


def form_records(records):
    """The connect form: CONNECT, CREATE (ndir 3) and MAIN MENU, status above them."""
    kept = [record for record in records if not is_create_record(record)]
    for record in kept:
        place_form_record(record)
    kept.append(make_sprite(VID_BUTTON, BUTTON_X, SECOND_BUTTON_Y, NDIR_3))
    kept.append(make_text(VID_STATIC_TEXT, LABEL_X, SECOND_BUTTON_Y - LABEL_RISE, 0,
                          FONT_LITERAL, "CREATE"))
    return kept


def lobby_records():
    """The room menu. The room list itself is drawn by the DLL (session_draw).

    - action button (ndir 1): the label is the script variable asmpStrAction
      (READY / NOT READY / START) in the button label font (VID 3, like LEAVE);
      its direction byte marks the room menu;
    - status text (VID 2, byte 0): the DLL writes room codes into its health;
    - leave button (ndir 2): the main menu script leaves the room on it.
    """
    return [
        make_sprite(VID_BUTTON, BUTTON_X, FIRST_BUTTON_Y, NDIR_1),
        make_sprite(VID_BUTTON, BUTTON_X, SECOND_BUTTON_Y, NDIR_2),
        make_text(VID_STATIC_TEXT, LABEL_X, FIRST_BUTTON_Y - LABEL_RISE, ROOM_MARKER_DIR,
                  FONT_VARIABLE, "asmpStrAction"),
        make_text(VID_STATIC_TEXT, LABEL_X, SECOND_BUTTON_Y - LABEL_RISE, 0, FONT_LITERAL,
                  "LEAVE"),
        make_text(VID_STATUS_TEXT, LABEL_X, STATUS_Y, 0, FONT_VARIABLE, "asmpStrConnecting"),
    ]


def describe(name, records):
    print(name)
    for record in records:
        x, y = struct.unpack_from("<ff", record.body, 8)
        text = record.text
        label = f" {ascii(text)}" if text is not None else ""
        print(f"  vid={record.vid:4} dir={record.direction:3} x={x:7.1f} y={y:7.1f}{label}")


def main(arguments):
    check_only = "--check" in arguments
    prefix, records = parse(FORM_PATH.read_bytes())

    form = form_records(records)
    lobby = lobby_records()
    outputs = {FORM_PATH: build(prefix, form), LOBBY_PATH: build(prefix, lobby)}

    if check_only:
        stale = [path.name for path, data in outputs.items()
                 if not path.exists() or path.read_bytes() != data]
        if stale:
            print("out of date: " + ", ".join(stale))
            return 1
        print("menus are up to date")
        return 0

    for path, data in outputs.items():
        path.write_bytes(data)
    describe(FORM_PATH.name, form)
    describe(LOBBY_PATH.name, lobby)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
